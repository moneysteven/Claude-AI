"""Signal rules: EMA crossover, filtered by the long-term trend and RSI.

BUY  when the fast EMA crosses above the slow EMA, price is above the
     trend EMA (uptrend), and RSI is between rsi_buy_min and rsi_buy_max
     (has momentum, not already overbought).
SELL when the fast EMA crosses below the slow EMA, price is below the
     trend EMA (downtrend), and RSI is between rsi_sell_min and rsi_sell_max.

Every signal comes with a stop-loss (ATR-based, so it adapts to how much
the market is currently moving) and a take-profit at reward_risk x the risk.
"""

from dataclasses import dataclass, asdict

import pandas as pd

from .indicators import atr, ema, rsi

DEFAULTS = {
    "ema_fast": 20,
    "ema_slow": 50,
    "ema_trend": 200,
    "rsi_length": 14,
    "rsi_buy_min": 50,
    "rsi_buy_max": 70,
    "rsi_sell_min": 30,
    "rsi_sell_max": 50,
    "atr_length": 14,
    "atr_stop_mult": 1.5,
    "reward_risk": 2.0,
}


@dataclass
class Signal:
    market: str
    side: str  # "BUY" or "SELL"
    time: pd.Timestamp
    entry: float
    stop: float
    target: float
    rsi: float
    reason: str

    def to_dict(self):
        d = asdict(self)
        d["time"] = self.time.isoformat()
        return d


def add_indicators(df, params):
    p = {**DEFAULTS, **(params or {})}
    out = df.copy()
    out["ema_fast"] = ema(out["close"], p["ema_fast"])
    out["ema_slow"] = ema(out["close"], p["ema_slow"])
    out["ema_trend"] = ema(out["close"], p["ema_trend"])
    out["rsi"] = rsi(out["close"], p["rsi_length"])
    out["atr"] = atr(out, p["atr_length"])
    above = out["ema_fast"] > out["ema_slow"]
    out["cross_up"] = above & ~above.shift(fill_value=True)
    out["cross_down"] = ~above & above.shift(fill_value=False)
    # Indicators need warm-up data before they mean anything.
    out["ready"] = pd.Series(range(len(out)), index=out.index) >= p["ema_trend"]
    return out


def signal_at(ind, i, market, params=None):
    """Return the Signal generated by closed candle number i, or None."""
    p = {**DEFAULTS, **(params or {})}
    row = ind.iloc[i]
    if not row["ready"]:
        return None
    risk = row["atr"] * p["atr_stop_mult"]
    if risk <= 0:
        return None
    close = row["close"]
    if row["cross_up"] and close > row["ema_trend"] and p["rsi_buy_min"] <= row["rsi"] <= p["rsi_buy_max"]:
        return Signal(
            market, "BUY", ind.index[i], close, close - risk, close + risk * p["reward_risk"], row["rsi"],
            f"EMA{p['ema_fast']} crossed above EMA{p['ema_slow']}, price above EMA{p['ema_trend']} "
            f"(uptrend), RSI {row['rsi']:.0f}",
        )
    if row["cross_down"] and close < row["ema_trend"] and p["rsi_sell_min"] <= row["rsi"] <= p["rsi_sell_max"]:
        return Signal(
            market, "SELL", ind.index[i], close, close + risk, close - risk * p["reward_risk"], row["rsi"],
            f"EMA{p['ema_fast']} crossed below EMA{p['ema_slow']}, price below EMA{p['ema_trend']} "
            f"(downtrend), RSI {row['rsi']:.0f}",
        )
    return None


def latest_signal(df, market, params=None):
    """Signal on the most recent closed candle, if any."""
    if len(df) == 0:
        return None
    return signal_at(add_indicators(df, params), len(df) - 1, market, params)
